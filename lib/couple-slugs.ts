// Shared slug logic for data/celebrity-couples.csv, used by the couples hub,
// compatibility pages and each celebrity's "Featured Relationships" block.
//
// The CSV stores display names, and slugifying a few of them doesn't produce
// the celebrity's real slug ("A$AP Rocky" → "a-ap-rocky", but the page is
// /asap-rocky). Every couple link built from those names 404'd — found
// 2026-10-15 in the sitemap link audit.
const NAME_SLUG_OVERRIDES: Record<string, string> = {
  'A$AP Rocky': 'asap-rocky',
  "A'ja Wilson": 'aja-wilson',
  'Catherine Princess of Wales': 'catherine-middleton',
  'Timothée Chalamet': 'timothee-hal-chalamet',
}

export function coupleNameToSlug(name: string): string {
  const n = name.trim()
  return NAME_SLUG_OVERRIDES[n] ?? n.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
}

